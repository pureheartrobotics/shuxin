def bd09mc_to_bd09ll(x: float, y: float) -> tuple[float, float]:
    """MC 坐标转 BD09 纬经度 (lat, lng)。"""
    abs_x = abs(float(x))
    abs_y = abs(float(y))
    coef = _MC2LL[-1]
    for idx, band in enumerate(_MCBAND):
        if abs_y >= band:
            coef = _MC2LL[idx]
            break
    lng = coef[0] + coef[1] * abs_x
    c = abs_y / coef[9]
    lat = (
        coef[2]
        + coef[3] * c
        + coef[4] * c * c
        + coef[5] * c**3
        + coef[6] * c**4
        + coef[7] * c**5
        + coef[8] * c**6
    )
    if float(x) < 0:
        lng = -lng
    if float(y) < 0:
        lat = -lat
    return lat, lng


def is_plausible_latlng(lat: float, lng: float) -> bool:
    """粗略校验坐标是否在中国境内附近。"""
    return 3.0 <= lat <= 55.0 and 73.0 <= lng <= 136.0
